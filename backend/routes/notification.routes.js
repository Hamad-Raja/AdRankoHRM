"use strict";
const router=require('express').Router(),authenticate=require('../src/middleware/authenticate');
const {csrfProtection}=require('../src/middleware/csrf'),ApiError=require('../src/utils/ApiError');
const schema=require('../src/validation/notification.validation'),service=require('../src/services/notification.service');
const parse=(s,v)=>{const r=s.safeParse(v);if(!r.success)throw new ApiError(400,'Invalid notification input.','VALIDATION_ERROR');return r.data;};
const run=work=>async(req,res,next)=>{try{res.json({success:true,data:await work(req)});}catch(e){next(e);}};
const empty=req=>parse(schema.empty,req.body||{});
router.use((req,res,next)=>{res.setHeader('Cache-Control','no-store');next();});router.use(authenticate());
router.get('/',run(req=>service.listNotifications(req.auth.user.id,parse(schema.listNotifications,req.query))));
router.get('/unread-count',run(req=>{parse(schema.empty,req.query);return service.getUnreadCount(req.auth.user.id);}));
router.post('/mark-all-read',csrfProtection,run(req=>{empty(req);return service.markAllAsRead(req.auth.user.id);}));
router.delete('/read',csrfProtection,run(req=>{empty(req);return service.clearReadNotifications(req.auth.user.id);}));
router.patch('/:id/read',csrfProtection,run(req=>{empty(req);return service.markAsRead(req.auth.user.id,parse(schema.id,req.params.id));}));
router.post('/:id/open',csrfProtection,run(req=>{empty(req);return service.openNotification(req.auth.user.id,parse(schema.id,req.params.id));}));
router.delete('/:id',csrfProtection,run(req=>{empty(req);return service.deleteNotification(req.auth.user.id,parse(schema.id,req.params.id));}));
module.exports=router;
